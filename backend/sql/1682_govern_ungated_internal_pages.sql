-- Bring the 37 ungoverned internal pages under Access Control.
--
-- Measured 2026-09-07: of 451 routes, 61 internal pages carried no page code at all. A page
-- with no code gets no page_catalog row, so it can never appear in /settings/access-control
-- and no grant can ever be created for it — the "many pages are not showing" report. 39 of
-- those also had no role list, meaning any authenticated user could open them.
--
-- Every one of their APIs was probed as a plain employee first and refuses or row-scopes
-- (signing certificates, fraud alerts, branch payroll HR, employees, feedback reports,
-- biometric summary, COSEC punches all 403; visitor visits 200 but scoped by actorScope).
-- So this closes a governance gap, not an active leak.
--
-- Two deliberate exclusions:
--   /dashboard — ProtectedRoute special-cases it so non-employees can reach the onboarding
--     request form. Gating it risks locking every not-yet-onboarded user out of the one page
--     they are allowed, so it stays ungated.
--   4 routes map onto codes that already exist and already carry grants (ONBOARDING_REQUESTS,
--     WFM_ATTENDANCE_EXCEPTIONS, ATTENDANCE_LOOKUP) — mapping only, no rows here.
--
-- Self-service pages are granted to every role that appears in role_page_access, which
-- reproduces exactly what they can reach today: this batch must not change anyone's access,
-- only make it visible and editable in Access Control. Tightening is then a UI action for an
-- administrator rather than a guess made here.
--
-- Sensitive pages instead get the role set their own API already enforces, so nobody loses
-- working functionality — anyone excluded was already receiving 403s from the backend.
--
-- INSERT IGNORE throughout; page_catalog has a UNIQUE on page_code and role_page_access on
-- (role_key, page_code), so re-running is a no-op.

