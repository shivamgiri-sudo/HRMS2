#!/usr/bin/env node
/**
 * Regenerate sql/MIGRATION_MANIFEST.lock.json from the live manifest.
 *
 * Run this ONLY when a manifest change is intended. The lock is what the CI
 * guard compares against, so regenerating it blindly defeats the guard — that is
 * the point of it being a deliberate, separate command rather than something a
 * test does for you.
 *
 * A deletion still fails the guard after regenerating unless the removed
 * filename is added to approvedDeletions with a reason. That is intentional: on
 * 2026-08-02 a stale working copy silently removed three other sessions'
 * manifest entries, and the only thing standing between that and a broken fresh
 * install was one person reading a diff.
 *
 *   node scripts/update-migration-lock.mjs            # show what would change
 *   node scripts/update-migration-lock.mjs --write    # write it
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LOCK_PATH = path.join(ROOT, "sql", "MIGRATION_MANIFEST.lock.json");
const WRITE = process.argv.includes("--write");

export function readManifest(root = ROOT) {
  const src = fs.readFileSync(path.join(root, "src", "db", "runPendingMigrations.ts"), "utf8");
  const start = src.indexOf("MIGRATION_MANIFEST");
  const end = src.indexOf("export type MigrationHealth");
  if (start < 0 || end < 0) throw new Error("Could not locate MIGRATION_MANIFEST in runPendingMigrations.ts");
  return [...src.slice(start, end).matchAll(/"([^"]+\.sql)"/g)].map((m) => m[1]);
}

export function readSqlFiles(root = ROOT) {
  return fs.readdirSync(path.join(root, "sql")).filter((f) => /\.sql$/.test(f)).sort();
}

const manifest = readManifest();
const files = readSqlFiles();
const fileSet = new Set(files);
const manifestSet = new Set(manifest);

const previous = fs.existsSync(LOCK_PATH)
  ? JSON.parse(fs.readFileSync(LOCK_PATH, "utf8"))
  : { released: [], approvedDeletions: [], knownDangling: [], knownUnlisted: [] };

const removed = previous.released.filter((f) => !manifestSet.has(f));
const added = manifest.filter((f) => !previous.released.includes(f));

const next = {
  $comment: "Generated by scripts/update-migration-lock.mjs. Do not hand-edit except to add an approvedDeletion with a reason.",
  generatedFrom: "backend/src/db/runPendingMigrations.ts MIGRATION_MANIFEST",
  released: manifest,
  approvedDeletions: previous.approvedDeletions ?? [],
  knownDangling: manifest.filter((m) => !fileSet.has(m)),
  knownUnlisted: files.filter((f) => !manifestSet.has(f)),
};

console.log(`manifest entries : ${manifest.length}`);
console.log(`sql files        : ${files.length}`);
console.log(`added since lock : ${added.length}${added.length ? " -> " + added.join(", ") : ""}`);
console.log(`REMOVED since lock: ${removed.length}${removed.length ? " -> " + removed.join(", ") : ""}`);
console.log(`dangling entries : ${next.knownDangling.length}${next.knownDangling.length ? " -> " + next.knownDangling.join(", ") : ""}`);
console.log(`unlisted files   : ${next.knownUnlisted.length}`);

if (removed.length) {
  const approved = new Set((next.approvedDeletions ?? []).map((d) => d.filename));
  const unapproved = removed.filter((f) => !approved.has(f));
  if (unapproved.length) {
    console.error(
      `\nRefusing to regenerate: ${unapproved.length} entr(y/ies) would be dropped without an approved deletion.\n` +
      unapproved.map((f) => `  ${f}`).join("\n") +
      `\n\nIf the removal is intended, add each to approvedDeletions in the lock with a reason and who approved it, then re-run.`,
    );
    process.exit(1);
  }
}

if (!WRITE) {
  console.log("\ndry run — pass --write to update the lock");
} else {
  fs.writeFileSync(LOCK_PATH, JSON.stringify(next, null, 2) + "\n");
  console.log(`\nwrote ${path.relative(ROOT, LOCK_PATH)}`);
}
